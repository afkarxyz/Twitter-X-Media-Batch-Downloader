pub fn color(family: &str, index: usize) -> egui::Color32 {
    let values = &FAMILIES
        .iter()
        .find(|(name, _)| *name == family)
        .unwrap_or(&FAMILIES[1])
        .1;
    let rgb = values[index.min(10)];
    egui::Color32::from_rgb((rgb >> 16) as u8, (rgb >> 8) as u8, rgb as u8)
}
